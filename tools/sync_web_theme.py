"""Export the shared Flutter design values used by the fnOS web renderer."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "flutter/lib/theme/fusion_theme.dart"
OUTPUT = ROOT / "fnos/frontend/fusion-theme.css"


def stylesheet():
    dart = SOURCE.read_text()
    values = dict(re.findall(r"static const (\w+) = (.*?);", dart))
    lines = ["/* Generated by tools/sync_web_theme.py from fusion_theme.dart. */", ":root {"]
    for name in ("primary", "onPrimary", "background", "onSurface", "onSurfaceVariant",
                 "outlineVariant", "surface", "surfaceContainerHigh", "inverseSurface",
                 "inverseOnSurface", "cardRadius", "fieldRadius", "cardSpacing", "blurRadius",
                 "settingsTint", "popupTint", "solidPanel", "panelBlur", "backdropHighlightLimit", "supportingText", "inactiveRail"):
        value = values[name]
        if match := re.fullmatch(r"Color\(0xFF([0-9A-F]{6})\)", value):
            css = "#" + match[1]
        elif match := re.fullmatch(r"Color\(0x([0-9A-F]{2})([0-9A-F]{6})\)", value):
            css = "#" + match[2] + match[1]
        elif value == "Colors.white":
            css = "#FFFFFF"
        else:
            css = f"{float(value):g}px"
        key = re.sub(r"([A-Z])", r"-\1", name).lower()
        lines.append(f"  --fusion-{key}: {css};")
    return "\n".join([*lines, "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = stylesheet()
    if args.check:
        if OUTPUT.read_text() != expected:
            parser.exit(1, "Run python3 tools/sync_web_theme.py to update fnOS theme.\n")
    else:
        OUTPUT.write_text(expected)
